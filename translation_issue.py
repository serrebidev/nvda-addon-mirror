#!/usr/bin/env python3
"""Manage the translation-gap issue fed by the mirror's translation audit.

The scheduled refresh runs ``audit_translations.py`` against the freshly
built catalog and hands the findings JSON to ``sync``, which creates the issue
when gaps exist, edits the existing one only when its content changed (so
mostly-clean runs do not spam the timeline), and closes it once the audit
passes. ``open`` and ``close`` remain for manual use.

All Forgejo access goes through the REST API with FORGEJO_TOKEN set; every
API call is injectable, which keeps the decision logic unit-testable.

    python translation_issue.py sync findings.json   # scheduled refresh
    python translation_issue.py open findings.json   # manual
    python translation_issue.py close                # manual
"""

import json
import os
import sys
import urllib.error
import urllib.request

ISSUE_TITLE = "Translation audit: add-ons still publishing non-English text"
ISSUE_LABEL = "translation-gap"
ISSUE_LABEL_COLOR = "e99695"
LABEL_DESCRIPTION = "Add-ons the mirror still publishes without English metadata"

DEFAULT_FORGEJO_HOST = "https://git.serrebiradio.com"
DEFAULT_FORGEJO_REPOSITORY = "serrebi/nvda-addon-mirror"


def _parse_api_body(response):
    """Read a Forgejo response as JSON, falling back to plain text."""
    text = response.read().decode("utf-8", "replace")
    try:
        return json.loads(text)
    except ValueError:
        return text


def default_api(method, path, payload=None):
    """Call the Forgejo REST API; return (status_code, parsed_body)."""
    token = os.environ.get("FORGEJO_TOKEN", "")
    if not token:
        raise RuntimeError(
            "FORGEJO_TOKEN is not set; cannot reach Forgejo issues"
        )
    host = os.environ.get("FORGEJO_HOST", DEFAULT_FORGEJO_HOST).rstrip("/")
    data = None
    headers = {
        "Accept": "application/json",
        "Authorization": f"token {token}",
    }
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(
        f"{host}/api/v1{path}", data=data, headers=headers, method=method
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status, _parse_api_body(response)
    except urllib.error.HTTPError as exc:
        try:
            detail = exc.read().decode("utf-8", "replace")
        except OSError:
            detail = ""
        return exc.code, detail


def _require_ok(method, path, status, data):
    """Raise unless a Forgejo API call answered 2xx."""
    if isinstance(status, int) and 200 <= status < 300:
        return data
    detail = data if isinstance(data, str) else json.dumps(data)[:300]
    raise RuntimeError(
        f"Forgejo {method} {path} failed with status {status}: {detail}"
    )


def _fenced(text):
    """Wrap text in a code fence long enough to survive backticks inside it."""
    fence = "```"
    while fence in text:
        fence += "`"
    return f"{fence}\n{text}\n{fence}"


#: Keep bodies bounded: a bounded body keeps edits cheap and the issue
#: history readable. Findings past the cap stay in the run log in full
#: (see log_queue), so nothing is lost.
MAX_BODY_CHARS = 60000


def render_body(findings, repository, host=None):
    """Render findings as the deterministic issue body."""
    host = (host or os.environ.get("FORGEJO_HOST", DEFAULT_FORGEJO_HOST)).rstrip("/")
    count = len(findings)
    noun = "add-on" if count == 1 else "add-ons"
    header = [
        f"The translation audit found {count} {noun} still publishing "
        "non-English text in the live mirror.",
        "",
        "To fix: add an English `summary` and `description` for each add-on "
        "ID below to `translations.json`, then let the next scheduled build "
        "publish them. `audit_translations.py` documents the detection "
        "rules; borrow style from the existing entries.",
        "",
        f"{len(findings)} untranslated {noun}:",
        "",
    ]
    footer = (
        "<sub>Generated by the mirror's "
        f"[scheduled refresh]({host}/{repository}). This issue closes "
        "automatically once the audit passes.</sub>"
    )
    body = "\n".join(header) + "\n"
    shown = 0
    for finding in findings:
        source = finding.get("sourceURL") or "no source URL"
        lines = [f"### `{finding['addonId']}` ({source})", ""]
        for field, detail in finding["fields"].items():
            text = " ".join((detail["text"] or "").split())
            if len(text) > 600:
                text = text[:597] + "..."
            lines.append(f"- `{field}` [{detail['reason']}]:")
            lines.append("")
            lines.append("  " + _fenced(text).replace("\n", "\n  "))
        lines.append("")
        block = "\n".join(lines) + "\n"
        if len(body) + len(block) + len(footer) + 200 > MAX_BODY_CHARS:
            break
        body += block
        shown += 1
    if shown < count:
        body += (
            f"...and {count - shown} more, left out to fit "
            "the issue size limit. Run `python audit_translations.py` "
            "for the full list.\n\n"
        )
    return body + footer


def _repository_path(repository):
    """Return the /repos/{owner}/{repo} API prefix for a slug."""
    repository = (
        repository
        or os.environ.get("FORGEJO_REPOSITORY", DEFAULT_FORGEJO_REPOSITORY)
    )
    return f"/repos/{repository.strip('/')}"


def _issue_number(issue):
    """Return an issue's per-repo number from a Forgejo issue object."""
    number = issue.get("number")
    if number is None:
        number = issue.get("index")
    return number


def find_open_issue(api=default_api, repository=None):
    """Return the number of the open gap issue, or None when there is none."""
    prefix = _repository_path(repository)
    # List and match locally rather than trusting search: the search index
    # lags newly created issues, so a run that follows a create too closely
    # would not find it and open a duplicate.
    status, data = api(
        "GET", f"{prefix}/issues?state=open&type=issues&limit=50"
    )
    issues = _require_ok("GET", "issues", status, data)
    for issue in issues or []:
        if issue.get("title") == ISSUE_TITLE:
            return _issue_number(issue)
    return None


def _label_id(api, repository):
    """Return the gap label's id, creating the label; None when that fails."""
    prefix = _repository_path(repository)
    try:
        status, data = api("GET", f"{prefix}/labels")
        labels = _require_ok("GET", "labels", status, data)
        for label in labels or []:
            if label.get("name") == ISSUE_LABEL:
                return label.get("id")
        status, data = api("POST", f"{prefix}/labels", {
            "name": ISSUE_LABEL,
            "color": f"#{ISSUE_LABEL_COLOR}",
            "description": LABEL_DESCRIPTION,
        })
        created = _require_ok("POST", "labels", status, data)
    except (RuntimeError, OSError):
        # An existing label makes the create fail, and a labels outage must
        # never block the issue itself; the issue is created unlabelled.
        return None
    return created.get("id") if isinstance(created, dict) else None


def open_issue(findings_path, api=default_api, repository=None):
    """Create or update the gap issue from a findings JSON file."""
    prefix = _repository_path(repository)
    with open(findings_path, "r", encoding="utf-8") as handle:
        findings = json.load(handle)
    body = render_body(findings, prefix.removeprefix("/repos/"))
    number = find_open_issue(api, prefix.removeprefix("/repos/"))
    if number is None:
        payload = {"title": ISSUE_TITLE, "body": body}
        label_id = _label_id(api, prefix.removeprefix("/repos/"))
        if label_id is not None:
            payload["labels"] = [label_id]
        status, data = api("POST", f"{prefix}/issues", payload)
        created = _require_ok("POST", "issues", status, data)
        url = created.get("html_url", "") if isinstance(created, dict) else ""
        print(f"Opened the translation-gap issue: {url}".rstrip())
        return
    status, data = api("GET", f"{prefix}/issues/{number}")
    if isinstance(status, int) and 200 <= status < 300:
        current = data.get("body", "") if isinstance(data, dict) else ""
        if current == body:
            print(f"Issue #{number} already matches the current findings.")
            return
    status, data = api("PATCH", f"{prefix}/issues/{number}", {"body": body})
    _require_ok("PATCH", f"issues/{number}", status, data)
    print(f"Updated issue #{number} with the current findings.")


def close_issue(api=default_api, repository=None):
    """Close the gap issue when the audit no longer finds untranslated text."""
    prefix = _repository_path(repository)
    number = find_open_issue(api, prefix.removeprefix("/repos/"))
    if number is None:
        print("No open translation-gap issue; nothing to close.")
        return
    status, data = api("POST", f"{prefix}/issues/{number}/comments", {
        "body": "The translation audit no longer finds untranslated "
        "add-ons; closing automatically.",
    })
    _require_ok("POST", f"issues/{number}/comments", status, data)
    status, data = api("PATCH", f"{prefix}/issues/{number}", {"state": "closed"})
    _require_ok("PATCH", f"issues/{number}", status, data)
    print(f"Closed issue #{number}.")


#: Prefix of the refresh-log lines the Muse cloud agent greps for. See
#: AGENTS.md "Muse cloud check". Changing it strands that agent: update both
#: together.
QUEUE_LOG_PREFIX = "TRANSLATION-QUEUE"


def log_queue(findings, out=None):
    """Write the translation queue into the scheduled run's log.

    The issue is the friendly view; the run log is the one that survives when
    the API cannot reach the issue (missing token, API outage, a body the
    server refuses). The Muse cloud agent reads these lines from the latest
    refresh log and adds the English itself. One JSON object per line,
    in full: the issue body truncates long text, this does not. ASCII-escaped
    JSON, so no console encoding can break the step; parsing restores the text.
    """
    out = out or sys.stdout
    if not findings:
        print(f"{QUEUE_LOG_PREFIX}-EMPTY", file=out)
        return
    print(f"{QUEUE_LOG_PREFIX}-BEGIN count={len(findings)}", file=out)
    for finding in findings:
        print(
            f"{QUEUE_LOG_PREFIX} "
            + json.dumps(finding, separators=(",", ":")),
            file=out,
        )
    print(f"{QUEUE_LOG_PREFIX}-END", file=out)
    # A marker line: greppable without downloading the full log.
    print(
        f"::warning title=Translation queue::{len(findings)} add-on(s) still "
        f"publish non-English text; the {QUEUE_LOG_PREFIX} lines in this log "
        "list them for the Muse cloud check",
        file=out,
    )


def sync_issue(findings_path, api=default_api, repository=None):
    """Make the gap issue match a findings file: open, update, or close.

    The queue is written to the run log first, so it is recorded even when
    every API call below fails.

    A missing findings file raises instead of closing, because a crashed
    audit must never close an issue that may still describe real gaps. The
    scheduled refresh absorbs that failure and the next run retries.
    """
    with open(findings_path, "r", encoding="utf-8") as handle:
        findings = json.load(handle)
    log_queue(findings)
    try:
        if findings:
            open_issue(findings_path, api, repository)
        else:
            close_issue(api, repository)
    except Exception as exc:
        # A marker line; the API error often is not one line.
        reason = " ".join(str(exc).split()) or type(exc).__name__
        print(
            f"::error title=Translation issue not updated::{reason}. The "
            f"{QUEUE_LOG_PREFIX} lines above are the queue of record.",
        )
        raise


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    valid = (
        len(argv) == 2 and argv[0] in ("sync", "open")
        or len(argv) == 1 and argv[0] == "close"
    )
    if not valid:
        print(__doc__, file=sys.stderr)
        return 2
    if argv[0] == "close":
        close_issue()
    else:
        handler = sync_issue if argv[0] == "sync" else open_issue
        handler(argv[1])
    return 0


if __name__ == "__main__":
    sys.exit(main())
